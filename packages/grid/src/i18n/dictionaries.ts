/** Fills each dictionary in from the English one. */
function mapValues(raw: Record<string, Dictionary>): Record<string, Dictionary> {
  const complete: Record<string, Dictionary> = {};
  for (const [code, dictionary] of Object.entries(raw)) {
    complete[code] = { ...DICTIONARY_EN_US, ...dictionary };
  }
  return complete;
}

