/**
 * The phrase dictionaries.
 *
 * Extracted from Handsontable's own language files so the keys and the wording
 * match exactly: a menu labelled differently in two libraries claiming the same
 * API is a difference a user notices before any of the interesting ones.
 *
 * A phrase is either one string or a pair — singular and plural — because
 * "Remove row" and "Remove rows" are the same command and one key.
 */

/** One phrase: a string, or `[singular, plural]`. */
export type Phrase = string | [string, string];

/** Every phrase for one language. */
export type Dictionary = Record<string, Phrase>;

